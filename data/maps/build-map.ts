// Builds data/maps/<id>.json from data/maps/<id>.spec.ts + its ASCII grid (see builder.ts).
// Building the current map also regenerates packages/contracts/src/map-ids.generated.ts (zone, door and pull-station
// ids), so the tool schemas and every Record<ZoneId, …> follow the map.
//
//   npm run data:map            # the current map
//   npm run data:map -- <id>    # another map spec
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildMap, loadFurnitureIndex, type MapSpec } from './builder.js';

/** The map the engine, server, web and dataset use. */
export const CURRENT_MAP_ID = 'office-v2';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const id = process.argv[2] ?? CURRENT_MAP_ID;

const spec = ((await import(`./${id}.spec.ts`)) as { default: MapSpec }).default;
const { map, summary } = buildMap(spec, here, loadFurnitureIndex(join(root, 'apps/web/public/assets/furniture')));
writeFileSync(join(here, `${id}.json`), JSON.stringify(map) + '\n');
for (const line of summary) console.log(line);

if (id === CURRENT_MAP_ID) {
  const list = (xs: string[]) => `[${xs.map((x) => `'${x}'`).join(', ')}]`;
  writeFileSync(
    join(root, 'packages/contracts/src/map-ids.generated.ts'),
    `// GENERATED by \`npm run data:map\` from data/maps/${id}.spec.ts — do not edit by hand.
export const DEFAULT_MAP_ID = '${id}';
export const ZONE_IDS = ${list(map.zones.map((z) => z.id))} as const;
export const DOOR_IDS = ${list(map.components.map((d) => d.id))} as const;
export const ALARM_STATION_IDS = ${list(map.alarms.map((a) => a.id))} as const;
`,
  );
  console.log('wrote packages/contracts/src/map-ids.generated.ts');
}
